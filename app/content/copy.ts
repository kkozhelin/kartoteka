const plural = (count: number, forms: [string, string, string]) => {
  const lastTwo = count % 100
  if (lastTwo >= 11 && lastTwo <= 14) return forms[2]
  const last = count % 10
  return last === 1 ? forms[0] : last >= 2 && last <= 4 ? forms[1] : forms[2]
}

